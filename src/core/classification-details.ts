/**
 * Text of the History and Cache detail panels for the two-stage fields (pure; the pages escape and render it).
 * Old entries have none of these fields, so every function degrades to the pre-two-stage output.
 */

import type { ClassificationResult } from '../types/index.ts';
import { toTriState } from './decision-thresholds.ts';
import { EXPLANATION_STALE_PENDING_MS } from './explanation.ts';

export const SYNTHESIZED_REASON_NOTE = 'Reason generated by the extension';
export const PROBABILITY_TITLE = 'Probability reported by the decision model';
export const EXPLANATION_PENDING_SUGGESTION = 'Not specified (explanation pending)';
const EXPLANATION_ERROR_DISPLAY_MAX_CHARS = 120;

/** A decision model answer with its probability: "Yes (93%)", "No (88%)", "Unknown (55% yes)". Null without a usable probability. */
export function formatProbabilityAnswer(probability: number | null | undefined, model?: string): string | null {
  if (typeof probability !== 'number' || !Number.isFinite(probability)) return null;
  const answer = toTriState(probability, model);
  if (answer === true) return `Yes (${Math.round(probability * 100)}%)`;
  if (answer === false) return `No (${Math.round((1 - probability) * 100)}%)`;
  return `Unknown (${Math.round(probability * 100)}% yes)`;
}

/** The decision model that classified the page (the exact build; the requested slug is added when it differs). Null for other sources. */
export function describeDecisionModel(c: ClassificationResult): string | null {
  if (c.source !== 'decision') return null;
  const exact = c.decision?.model ?? c.model ?? 'Unknown model';
  const requested = c.decision?.requestedModel;
  return requested && requested !== exact ? `${exact} (requested: ${requested})` : exact;
}

export interface ExplanationModelLabel {
  text: string;
  failed: boolean;
}

/** Stage 2 row: the explanation model, "Pending…", or "Failed (<error>)". Null when no explanation was attempted. */
export function describeExplanationModel(c: ClassificationResult, now: number): ExplanationModelLabel | null {
  const generative = c.generative;
  if (!generative) return null;
  if (generative.status === 'done') {
    return { text: generative.model || 'Unknown model', failed: false };
  }
  if (generative.status === 'pending' && now - generative.attemptedAt < EXPLANATION_STALE_PENDING_MS) {
    return { text: 'Pending…', failed: false };
  }
  // failed, or a pending marker old enough to mean the worker died
  const error = (generative.error ?? '').trim().slice(0, EXPLANATION_ERROR_DISPLAY_MAX_CHARS);
  return { text: error ? `Failed (${error})` : 'Failed', failed: true };
}

/** True while a fresh Stage 2 attempt is running (the suggestion row must not show the stale placeholder). */
export function isExplanationPending(c: ClassificationResult, now: number): boolean {
  const generative = c.generative;
  return generative?.status === 'pending' && now - generative.attemptedAt < EXPLANATION_STALE_PENDING_MS;
}

/** Suggestion row value when there is no link. */
export function describeMissingSuggestion(c: ClassificationResult, now: number): string {
  if (isExplanationPending(c, now)) return EXPLANATION_PENDING_SUGGESTION;
  const reason = (c.noUrlReason || '').trim();
  return reason ? `Not specified (${reason})` : 'Not specified';
}

/** Whether the reason was written by the extension rather than by a model. */
export function isSynthesizedReason(c: ClassificationResult): boolean {
  return c.reasonSource === 'synthesized';
}
